-- Namaste Tripathi — config, orders and rides
--
-- Closes the three gaps left by the initial schema: placing a food order and
-- booking a ride now have somewhere to go, and the app's taxonomy (service
-- tiles, filter chips, saved addresses, ride classes, editorial copy) moves
-- out of the Dart source so it can be edited without shipping a build.
--
-- Config tables follow the catalogue's rules: world-readable, written only
-- from the dashboard. Orders and rides follow the bookings' rules: one row
-- per user, invisible to everyone else.

-- ------------------------------------------------------------ config tables

-- The service tiles. `is_wide` marks the full-width one, so the grid tiles
-- and the wide tile stay one editable list.
create table if not exists public.service_categories (
  id         text primary key,
  label      text not null,
  icon       text not null default 'settings',
  is_wide    boolean not null default false,
  sort_order integer not null default 0
);

create table if not exists public.saved_places (
  id         text primary key,
  icon       text not null default 'home',
  label      text not null,
  address    text not null default '',
  sort_order integer not null default 0
);

create table if not exists public.ride_options (
  id           text primary key,
  title        text not null,
  subtitle     text not null default '',
  icon         text not null default 'two_wheeler',
  color        text not null default '#8A5A00',
  eta          text not null default '',
  price_per_km integer not null default 10,
  sort_order   integer not null default 0
);

-- The filter chip rows, one row per chip. `group_key` matches
-- `FilterGroup` in the app: cuisine, hotel, property, provider.
create table if not exists public.filter_options (
  id         bigint generated by default as identity primary key,
  group_key  text not null,
  label      text not null,
  sort_order integer not null default 0,
  unique (group_key, label)
);

create index if not exists filter_options_group_key_idx
  on public.filter_options (group_key, sort_order);

-- Loose editorial strings that have no table of their own, such as the
-- traveler tip on the bookings screen.
create table if not exists public.app_settings (
  key        text primary key,
  value      text not null default '',
  updated_at timestamptz not null default now()
);

-- ------------------------------------------------------------------- orders

-- The bill is stored as it was at checkout, not recomputed from today's
-- menu: `lines` is a frozen jsonb snapshot of what was ordered and what it
-- cost, so a later price change cannot rewrite history.
create table if not exists public.orders (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  restaurant_id   text not null default '',
  restaurant_name text not null default '',
  image           text not null default '',
  lines           jsonb not null default '[]'::jsonb,
  subtotal        numeric(10, 2) not null default 0,
  delivery_fee    numeric(10, 2) not null default 0,
  taxes           numeric(10, 2) not null default 0,
  discount        numeric(10, 2) not null default 0,
  total           numeric(10, 2) not null default 0,
  payment_method  text not null default 'gpay',
  coupon_code     text,
  instructions    text[] not null default '{}',
  status          text not null default 'placed'
                    check (status in ('placed', 'preparing', 'on_the_way',
                                      'delivered', 'cancelled')),
  reference       text,
  created_at      timestamptz not null default now()
);

create index if not exists orders_user_id_created_at_idx
  on public.orders (user_id, created_at desc);

-- -------------------------------------------------------------------- rides

create table if not exists public.rides (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null default auth.uid() references auth.users (id) on delete cascade,
  option_id    text not null default '',
  ride_type    text not null default '',
  from_address text not null default '',
  to_address   text not null default '',
  distance_km  numeric(6, 2) not null default 0,
  fare         integer not null default 0,
  eta          text not null default '',
  status       text not null default 'searching'
                 check (status in ('searching', 'assigned', 'completed',
                                   'cancelled')),
  reference    text,
  created_at   timestamptz not null default now()
);

create index if not exists rides_user_id_created_at_idx
  on public.rides (user_id, created_at desc);

-- ---------------------------------------------------------------------- RLS

alter table public.service_categories enable row level security;
alter table public.saved_places       enable row level security;
alter table public.ride_options       enable row level security;
alter table public.filter_options     enable row level security;
alter table public.app_settings       enable row level security;
alter table public.orders             enable row level security;
alter table public.rides              enable row level security;

-- Config: read-only for everyone, same as the catalogue. The app reads it
-- with the anon key before anyone signs in, so `anon` is included.
do $$
declare
  t text;
begin
  foreach t in array array[
    'service_categories', 'saved_places', 'ride_options', 'filter_options',
    'app_settings'
  ]
  loop
    execute format(
      'drop policy if exists %I on public.%I', t || '_read_all', t);
    execute format(
      'create policy %I on public.%I for select to anon, authenticated using (true)',
      t || '_read_all', t);
  end loop;
end
$$;

-- Orders and rides: owner-only. No delete policy — a placed order is a
-- record, so it is cancelled by status rather than removed.
do $$
declare
  t text;
begin
  foreach t in array array['orders', 'rides']
  loop
    execute format('drop policy if exists %I on public.%I', t || '_select_own', t);
    execute format(
      'create policy %I on public.%I for select to authenticated using (auth.uid() = user_id)',
      t || '_select_own', t);

    execute format('drop policy if exists %I on public.%I', t || '_insert_own', t);
    execute format(
      'create policy %I on public.%I for insert to authenticated with check (auth.uid() = user_id)',
      t || '_insert_own', t);

    execute format('drop policy if exists %I on public.%I', t || '_update_own', t);
    execute format(
      'create policy %I on public.%I for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id)',
      t || '_update_own', t);
  end loop;
end
$$;

